/** 2×2 avatar stack — how the app renders a group conversation's icon. */
export const AvatarStack: React.FC<{ agents: Agent[]; size: number }> = ({ agents, size }) => {
  const s = size * 0.56;
  const gap = size - s;
  return (
    <div style={{ position: "relative", width: size, height: size, flexShrink: 0 }}>
      {agents.slice(0, 4).map((a, i) => (
        <AgentAvatar
          key={a.file + i}
          agent={a}
          size={s}
          style={{
            position: "absolute",
            left: (i % 2) * gap,
            top: Math.floor(i / 2) * gap,
            border: `${Math.max(1.5, size * 0.02)}px solid ${T.card}`,
          }}
        />
      ))}
    </div>
  );
};

