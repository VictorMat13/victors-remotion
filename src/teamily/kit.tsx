/** Pill chip — matches the real category / filter chips. */
export const TChip: React.FC<{
  label: string;
  tone?: "neutral" | "green" | "solid" | "grey" | "amber";
  size?: number;
  style?: React.CSSProperties;
}> = ({ label, tone = "neutral", size = 26, style }) => {
  const tones = {
    neutral: { bg: T.card, fg: T.ink, bd: T.line },
    green: { bg: T.greenTint, fg: T.greenText, bd: T.greenLine },
    solid: { bg: T.green, fg: "#FFFFFF", bd: T.green },
    grey: { bg: T.greySoft, fg: T.grey, bd: T.lineSoft },
    amber: { bg: T.amberSoft, fg: T.amber, bd: "#FDE68A" },
  }[tone];
  return (
    <div
      style={{
        display: "inline-flex",
        alignItems: "center",
        gap: 8,
        padding: `${Math.round(size * 0.44)}px ${Math.round(size * 0.86)}px`,
        borderRadius: R.full,
        background: tones.bg,
        border: `1.5px solid ${tones.bd}`,
        color: tones.fg,
        fontFamily: FONT,
        fontSize: size,
        fontWeight: 600,
        whiteSpace: "nowrap",
        ...style,
      }}
    >
      {label}
    </div>
  );
};

