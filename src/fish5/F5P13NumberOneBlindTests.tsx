              const aEnd = i < 2 ? ACT[i + 1] : TRI_AT;
              const glow = interpolate(
                frame,
                [aStart, aStart + 10, aEnd, aEnd + 12],
                [0, 1, 1, 0.45],
                {
                  extrapolateLeft: "clamp",
                  extrapolateRight: "clamp",
                },
              );
              const bump =
                frame >= aStart && frame <= aStart + 16
                  ? Math.sin((Math.PI * (frame - aStart)) / 16)
                  : 0;
