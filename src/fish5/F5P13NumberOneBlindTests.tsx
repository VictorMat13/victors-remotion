// ---------------------------------------------------------------------------
// Deterministic helpers + waveform silhouettes (pure functions of t / i)
// ---------------------------------------------------------------------------
const fract = (x: number) => x - Math.floor(x);
const rnd = (i: number) => fract(Math.sin((i + 1) * 12.9898) * 43758.5453);
const bell = (t: number, c: number, s: number) =>
  Math.exp(-((t - c) * (t - c)) / (2 * s * s));
const clamp01 = (v: number) => Math.min(1, Math.max(0, v));

type StageK = "neutral" | "op" | "ed" | "lg" | "tri";

// idle murmur — low, even
const envNeutral = (t: number) => 0.14 + 0.05 * Math.sin(t * 8 + 1);
// blunt, impatient — jagged spikes, front-loaded, hard gaps
const envOp = (t: number, i: number) => {
  const spik = Math.pow(Math.abs(Math.sin(t * 22 + 0.8)), 0.6);
  const chop = 0.55 + 0.45 * rnd(i * 7 + 3);
  return (0.26 + 0.66 * spik * chop) * (1.06 - 0.22 * t);
};
// quiet, unhurried — one low smooth swell, small tail
const envEd = (t: number) =>
  0.1 + 0.3 * bell(t, 0.42, 0.14) + 0.1 * bell(t, 0.8, 0.06);
// measured, amused — moderate undulation rising into a question-lift
const envLg = (t: number) =>
  0.28 + 0.13 * Math.sin(t * 11 + 0.4) + 0.24 * t * t;
// settle payoff — same line as three different people, one segment each
const SEG_GAP = 0.024;
const envTri = (t: number, i: number) => {
  if (Math.abs(t - 1 / 3) < SEG_GAP || Math.abs(t - 2 / 3) < SEG_GAP)
    return 0.07;
  if (t < 1 / 3) return envOp(t * 3, i) * 0.8;
  if (t < 2 / 3) return envEd((t - 1 / 3) * 3) * 1.25;
  return envLg((t - 2 / 3) * 3) * 0.92;
};

const envFor = (k: StageK, t: number, i: number): number => {
  switch (k) {
    case "neutral":
      return envNeutral(t);
    case "op":
      return envOp(t, i);
    case "ed":
      return envEd(t);
    case "lg":
      return envLg(t);
    case "tri":
      return envTri(t, i);
  }
};

const colorFor = (k: StageK, t: number): string => {
  switch (k) {
    case "neutral":
      return ALTARI.faint;
    case "op":
      return CHIPS[0].accent;
    case "ed":
      return CHIPS[1].accent;
    case "lg":
      return CHIPS[2].accent;
    case "tri":
      return t < 1 / 3
        ? CHIPS[0].accent
        : t < 2 / 3
          ? CHIPS[1].accent
          : CHIPS[2].accent;
  }
};

// Stage machine: which silhouette we are morphing from/to at this frame
const stageAt = (frame: number): { from: StageK; to: StageK; p: number } => {
  const steps: Array<[number, StageK]> = [
    [ACT[0], "op"],
    [ACT[1], "ed"],
    [ACT[2], "lg"],
    [TRI_AT, "tri"],
  ];
  let idx = -1;
  for (let s = 0; s < steps.length; s++) {
    if (frame >= steps[s][0]) idx = s;
  }
  if (idx === -1) return { from: "neutral", to: "neutral", p: 1 };
  const from: StageK = idx === 0 ? "neutral" : steps[idx - 1][1];
  const p = Easing.out(Easing.cubic)(clamp01((frame - steps[idx][0]) / MORPH));
  return { from, to: steps[idx][1], p };
};

// Parallax stars (fish4 starfield language) — deterministic, subtle
const buildStars = () => {
  const pts = [];
  for (let i = 0; i < 26; i++) {
    pts.push({
      x: 60 + rnd(i * 3 + 1) * 1700,
      y: 40 + rnd(i * 5 + 2) * 1720,
      r: 0.9 + rnd(i * 7 + 3) * 1.7,
      o: 0.1 + rnd(i * 11 + 4) * 0.22,
      ph: rnd(i * 13 + 5) * Math.PI * 2,
    });
  }
  return pts;
};

